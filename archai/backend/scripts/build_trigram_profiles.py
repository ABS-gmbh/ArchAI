"""Build lexical trigram profiles from the CATMuS Medieval train split.

Usage::

    python scripts/build_trigram_profiles.py --out profiles.json                 # read the text columns over HTTP
    python scripts/build_trigram_profiles.py --data DIR --out profiles.json      # or from downloaded parquet files

Reads only the ``text`` and ``language`` columns of the train split of the
Hugging Face dataset ``CATMuS/medieval`` (CC-BY 4.0, revision pinned below),
never its images and never its test split: the held-out benchmark
(``eval/heldout/``) samples the test manuscripts, which are disjoint from the
train ones. The choices were fixed before any measurement and nothing was tuned:

- each line goes through the tokenisation the quality gate scores with
  (``lexicon_trust``: the search key, words of three letters or more, their
  trigrams);
- a profile is the ``--top`` (100) most frequent trigrams of a language, the
  same order of size as the hand-picked Latin and French profiles (73-102);
  ties keep the order the trigrams were first seen in, with the files read in
  sorted order;
- no threshold of the gate is touched.

The Spanish and Dutch profiles in ``app/services/lexicon_trust.py`` were
generated by this script; ``--python`` prints them as they are committed.

The output lists, per language, the manuscripts and lines used, the trigrams,
and the share of the language's own trigrams a profile covers.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

REPO = "datasets/CATMuS/medieval"
REVISION = "e11965909ba89dea89476f665fc4d8541b0bf7a1"
# CATMuS language value -> the gate's normalised language name.
LANGUAGES = {
    "Castilian": "spanish",
    "Catalan": "catalan",
    "Italian": "italian",
    "Middle Dutch": "dutch",
    "Occitan": "occitan",
    "Galician": "portuguese",
}


def _train_files(data: Path | None) -> list[tuple[str, object]]:
    if data is not None:
        return [(str(p), None) for p in sorted((data / "train").glob("*.parquet"))]
    from huggingface_hub import HfFileSystem

    fs = HfFileSystem()
    paths = sorted(fs.glob(f"{REPO}@{REVISION}/train/*.parquet"))
    return [(p, fs) for p in paths]


def profile_from_texts(texts, top: int) -> list[str]:
    """The *top* most frequent gate trigrams of *texts*, sorted."""
    from app.services.lexicon_trust import _key_tokens, _token_trigrams

    counter: Counter = Counter()
    for text in texts:
        counter.update(_token_trigrams(_key_tokens(text or "")))
    return sorted(trigram for trigram, _ in counter.most_common(top))


def build(data: Path | None, top: int) -> dict:
    import pyarrow.parquet as pq

    from app.services.lexicon_trust import _key_tokens, _token_trigrams

    counts: dict[str, Counter] = defaultdict(Counter)
    lines: Counter = Counter()
    manuscripts: dict[str, set] = defaultdict(set)
    for path, fs in _train_files(data):
        name = path.rsplit("/", 1)[-1]
        if not re.match(r"L-(Cas|Cat|Ita|Mid_Dut|Occ|Gal)\.", name):
            continue
        table = pq.read_table(path, columns=["text", "language", "shelfmark"], filesystem=fs)
        for rec in table.to_pylist():
            language = LANGUAGES.get(rec["language"])
            if language is None:
                continue
            counts[language].update(_token_trigrams(_key_tokens(rec["text"] or "")))
            lines[language] += 1
            manuscripts[language].add(rec["shelfmark"])
        print(f"{name}: read", flush=True)
    out = {"source": f"hf://{REPO}@{REVISION} train split", "top": top, "profiles": {}}
    for language, counter in sorted(counts.items()):
        total = sum(counter.values())
        chosen = [trigram for trigram, _ in counter.most_common(top)]  # as profile_from_texts
        out["profiles"][language] = {
            "trigrams": sorted(chosen),
            "lines": lines[language],
            "manuscripts": sorted(manuscripts[language]),
            "trigram_tokens": total,
            "coverage": round(sum(counter[t] for t in chosen) / total, 4) if total else 0.0,
        }
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--data", type=Path, help="a directory with train/*.parquet; default: read over HTTP")
    parser.add_argument("--top", type=int, default=100)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--python", action="store_true", help="also print the profiles as committed in lexicon_trust.py")
    args = parser.parse_args(argv)
    result = build(args.data, args.top)
    if args.python:
        for language, profile in result["profiles"].items():
            print(f'_TRIGRAM_PROFILES["{language}"] = frozenset({sorted(profile["trigrams"])!r})')
    args.out.write_text(json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for language, profile in result["profiles"].items():
        print(f"{language}: {len(profile['manuscripts'])} manuscripts, {profile['lines']} lines, coverage {profile['coverage']:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
